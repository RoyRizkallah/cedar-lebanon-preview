// Reads each command's parameters from its source, so the slot table can be generated and checked.
// (Built code renames parameters, so the app never reads them at runtime; it uses the generated table.)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

function parameters(fn) {
  const source = fn.toString();
  const start = source.indexOf('(');
  let depth = 0, end = start;
  for (let i = start; i < source.length; i++) {
    if ('([{'.includes(source[i])) depth++;
    else if (')]}'.includes(source[i]) && --depth === 0) { end = i; break; }
  }
  const names = [];
  let part = '', level = 0;
  for (const char of source.slice(start + 1, end)) {
    if ('([{'.includes(char)) level++;
    if (')]}'.includes(char)) level--;
    if (char === ',' && level === 0) { names.push(part); part = ''; } else part += char;
  }
  if (part.trim()) names.push(part);
  // A destructured options object is kept whole; a plain parameter loses its default value.
  return names.map(name => (name.trim().startsWith('{') ? name.trim() : name.split('=')[0].trim())).slice(1);
}
// A parameter named staffId is the actor; an options object that carries staffId gets the actor written into it.
const slotOf = name => (name === 'staffId' || name === 'by' ? 'me' : name === 'now' ? 'now' : name.startsWith('{') && /\bstaffId\b/.test(name) ? 'arg+me' : 'arg');

export const slotsFromSource = functions => Object.fromEntries(Object.entries(functions).map(([name, fn]) => [name, parameters(fn).map(slotOf)]));

export const SLOT_FILE = fileURLToPath(new URL('../../src/lib/commandSlots.js', import.meta.url));
export function render(slots) {
  const rows = Object.entries(slots).map(([name, list]) => `  ${name}: ${JSON.stringify(list).replace(/"/g, "'").replace(/,/g, ', ')}`);
  return `// Generated by scripts/gen-command-slots.mjs from each function's parameters. Do not edit by hand.\nexport const SLOTS = {\n${rows.join(',\n')}\n};\n`;
}
export const writeSlots = slots => writeFileSync(SLOT_FILE, render(slots));
